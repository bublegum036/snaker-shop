-- Seven teaching tables. Run inside an isolated schema; no DROP statements.
CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    hashed_password text NOT NULL,
    is_admin boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE brands (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);
CREATE TABLE products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(btrim(name)) > 0),
    brand_id integer NOT NULL REFERENCES brands(id),
    description text NOT NULL DEFAULT '',
    price numeric(10,2) NOT NULL CHECK (price > 0),
    image_url text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE product_sizes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL REFERENCES products(id),
    size numeric(4,1) NOT NULL CHECK (size > 0),
    stock integer NOT NULL CHECK (stock >= 0),
    UNIQUE (product_id, size)
);
CREATE TABLE cart_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id),
    product_size_id integer NOT NULL REFERENCES product_sizes(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    UNIQUE (user_id, product_size_id)
);
CREATE TABLE orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id),
    status text NOT NULL DEFAULT 'created'
        CHECK (status IN ('created', 'processing', 'completed')),
    total numeric(12,2) NOT NULL CHECK (total >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE order_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL REFERENCES orders(id),
    product_size_id integer NOT NULL REFERENCES product_sizes(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    price_at_purchase numeric(10,2) NOT NULL CHECK (price_at_purchase > 0)
);
